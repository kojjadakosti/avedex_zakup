#!/usr/bin/env node
/**
 * Read-only preflight for a Supabase data-only dump before restoring to
 * a fresh self-hosted database. Never print SQL rows or credentials.
 *
 * Storage objects are migrated via S3/rclone, so importing stale
 * storage.objects metadata would create records without local file bytes.
 */
import { createReadStream } from "node:fs";
import { createInterface } from "node:readline";

const file = process.argv[2];
if (!file) {
  console.error("Usage: node scripts/storage-dump-preflight.mjs <data.sql>");
  process.exit(64);
}

const reader = createInterface({
  input: createReadStream(file, { encoding: "utf8" }),
  crlfDelay: Infinity,
});

let sourceObjectsPresent = false;
let authUsersPresent = false;
let sourceBucketsPresent = false;
let sourceVaultPresent = false;
let sourceCronPresent = false;
let vectorStoragePresent = false;
let statementCount = 0;

// Recognize COPY and INSERT. Dump generated by Supabase CLI with --use-copy.
const copyPattern = /^\s*(?:COPY|INSERT\s+INTO)\s+(?:"?(\w+)"?\.)?"?(\w+)"?\b/i;

try {
  for await (const line of reader) {
    const match = copyPattern.exec(line);
    if (!match) continue;
    statementCount++;
    const schema = (match[1] || "public").toLowerCase();
    const table = match[2].toLowerCase();
    if (schema === "storage" && table === "objects") sourceObjectsPresent = true;
    if (schema === "storage" && table === "buckets") sourceBucketsPresent = true;
    if (schema === "auth" && table === "users") authUsersPresent = true;
    if (schema === "vault" && table === "secrets") sourceVaultPresent = true;
    if (schema === "cron" && table === "job") sourceCronPresent = true;
    if (schema === "storage" && ["buckets_vectors", "vector_indexes"].includes(table)) vectorStoragePresent = true;
  }
} catch (error) {
  console.error("Cannot examine SQL dump:", error instanceof Error ? error.code || error.name : "Unknown error");
  process.exitCode = 66;
}

if (process.exitCode) process.exit();
console.log(JSON.stringify({
  checked: true,
  statements: statementCount,
  authUsersPresent,
  storageBucketsPresent: sourceBucketsPresent,
  storageObjectsPresent: sourceObjectsPresent,
  vaultSecretsPresent: sourceVaultPresent,
  databaseCronPresent: sourceCronPresent,
  vectorStorageTablesPresent: vectorStoragePresent,
}));

if (sourceObjectsPresent) {
  console.error(
    "BLOCKED: data.sql includes storage.objects. Exclude this table when dumping " +
    "and transfer file contents through S3; never import stale file metadata."
  );
  process.exitCode = 2;
} else if (!authUsersPresent) {
  console.error("BLOCKED: auth.users is absent from data.sql. Existing staff logins might be lost.");
  process.exitCode = 3;
} else if (sourceVaultPresent) {
  console.error(
    "BLOCKED: data.sql includes vault.secrets. Encrypted values cannot " +
    "be trusted under a different self-hosted encryption key."
  );
  process.exitCode = 4;
} else if (sourceCronPresent) {
  console.error(
    "BLOCKED: data.sql includes cron.job. The restored database must " +
    "not automatically call old Vercel destinations."
  );
  process.exitCode = 5;
} else if (vectorStoragePresent) {
  console.error(
    "BLOCKED: data.sql includes vector Storage COPY tables. " +
    "Remove only verified EMPTY blocks using prepare-restore-dump.mjs."
  );
  process.exitCode = 6;
}
